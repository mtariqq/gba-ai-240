# === Day 5: GBA Home Loan EMI Calculator - Hong Kong Banking ===
print("===HSBC GBA Home Loan - Hong Kong / Shenzhen===")

# Client Input
client_name = input("Client Name: ")
loan_amount = float(input("Loan Amount in CNY: "))
annual_rate = float(input("Annual Interest Rate % (e.g 4.5): "))
years = int(input("Loan Years: "))

# Calculation - Bank Logic
monthly_rate = annual_rate / 12 / 100
total_months = years * 12

# EMI Formula
emi = loan_amount * monthly_rate * (1 + monthly_rate)**total_months / ((1 + monthly_rate)**total_months - 1)
total_payment = emi * total_months
total_interest = total_payment - loan_amount

# CNY to HKD for GBA Client
cny_to_hkd = 1.8
print(f"\n---Loan Report for {client_name}---")
print(f"Monthly EMI: {emi:.2f} CNY / {emi * cny_to_hkd:.2f} HKD")
print(f"Total Interest: {total_interest:.2f} CNY")
print(f"Total Payment: {total_payment:.2f} CNY")
print(f"Loan for {years} years = {total_months} months")

if emi < 10000:
    print("Status: EASY EMI - Approved Quickly")
else:
    print("Status: HIGH EMI - Need Higher Income Check")
print("===Report Generated by Hong Kong GBA System===")
